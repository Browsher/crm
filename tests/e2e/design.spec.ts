test('abas e sobreposições usam foco e medidas do design system no CSS produtivo', async ({ page }) => {
  await entrar(page, 'gestor')
  await page.goto('/design')
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
  await page.getByLabel('Tema do design system').selectOption('dark')
  const titulo = page.getByRole('heading', { level: 1 })
  await expect(titulo).toHaveCSS('font-size', '28px')
  await expect(titulo).toHaveCSS('line-height', '36px')
  await expect(page.getByRole('main')).toHaveCSS('padding-top', '30px')
  await expect(page.getByRole('main')).toHaveCSS('padding-left', '32px')
  const recolher = page.getByRole('button', { name: 'Recolher barra lateral' })
  expect((await recolher.boundingBox())!.width).toBeGreaterThanOrEqual(40)
  await recolher.click()
  await expect(page.locator('aside')).toHaveCSS('width', '76px')
  await page.getByRole('button', { name: 'Expandir barra lateral' }).click()
  const dados = page.getByRole('tab', { name: 'Dados da empresa', exact: true })
  const historico = page.getByRole('tab', { name: 'Histórico', exact: true })
  const nota = page.getByLabel('Nota da ficha')
  await nota.fill('Rascunho preservado entre abas')
  await dados.focus()
  await page.keyboard.press('ArrowRight')
  await expect(historico).toBeFocused()
  await expect(historico).toHaveCSS('outline-width', '3px')
  await expect(historico).toHaveCSS('outline-offset', '3px')
  await expect(historico).toHaveCSS('box-shadow', 'none')
  await expect(historico).toHaveCSS('min-height', '40px')
  await page.keyboard.press('Tab')
  await expect(historico).not.toBeFocused()
  await dados.click()
  await expect(nota).toHaveValue('Rascunho preservado entre abas')
  await page.getByRole('button', { name: 'Próxima', exact: true }).click()
  const dialogo = page.getByRole('dialog', { name: 'Trocar de empresa e descartar as anotações?' })
  await expect(dialogo).toHaveCSS('border-radius', '10px')
  await expect(dialogo).toHaveCSS('padding-top', '24px')
  await expect(dialogo).toHaveCSS('background-color', 'rgb(28, 36, 45)')
  const cancelar = dialogo.getByRole('button', { name: 'Cancelar', exact: true })
  await cancelar.focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Shift+Tab')
  await expect(cancelar).toHaveCSS('outline-width', '3px')
  await expect(cancelar).toHaveCSS('box-shadow', 'none')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(dialogo).toHaveCSS('padding-top', '20px')
  const fechar = dialogo.getByRole('button', { name: 'Fechar', exact: true })
  expect((await fechar.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await page.screenshot({ path: '.superpowers/sdd/2026-10-27-padronizacao-elementos-crm/task-4-captures/dialogo-mobile-dark.png' })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Menu do CRM' }).click()
  const menu = page.getByRole('dialog', { name: 'Navegação do CRM' })
  await expect(menu).toHaveCSS('background-color', 'rgb(28, 36, 45)')
  const fecharMenu = menu.getByRole('button', { name: 'Fechar', exact: true })
  await fecharMenu.focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Shift+Tab')
  await expect(fecharMenu).toHaveCSS('outline-width', '3px')
  await expect(fecharMenu).toHaveCSS('outline-offset', '3px')
  await expect(fecharMenu).toHaveCSS('box-shadow', 'none')
  await page.screenshot({ path: '.superpowers/sdd/2026-10-27-padronizacao-elementos-crm/task-4-captures/menu-mobile-dark.png' })
})
