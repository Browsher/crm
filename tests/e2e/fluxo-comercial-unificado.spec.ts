import { expect, test, type Page } from '@playwright/test'
import { bancoGruposDoHarness, comBancoGrupos } from './dados-grupos'
import { criarUsuarioComSenha } from '../integracao/ajuda'
import { vincularEmpresaTeste } from '../integracao/atendimento-fixtures'

const empresa = '00000000-0000-4000-8000-000000009950'
const sql = (texto: string, valores: unknown[] = []) => comBancoGrupos(c => c.query(texto, valores))
async function entrar(page: Page) {
  await page.goto('/login')
  await page.getByLabel('E-mail').fill('fluxounificadoe2e@teste.local')
  await page.getByLabel('Senha', { exact: true }).fill('Senha-e2e-2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL('/meu-dia')
}
test.beforeAll(async () => {
  const banco = bancoGruposDoHarness()
  const eu = await criarUsuarioComSenha(banco, 'vendedor', 'fluxounificadoe2e', 'Senha-e2e-2026', { pendente: false })
  await banco.sql("INSERT INTO empresa(id,razao_social,telefone) VALUES($1,'Fluxo Integrado','11988889950')", [empresa])
  await vincularEmpresaTeste(banco, empresa, eu.id, 'legado')
})

test('vínculo atravessa contato, agenda, arquivo, retomada e vendas; aba antiga não vende cliente arquivado', async ({ page, context }) => {
  await entrar(page)
  await page.goto('/fila/localizar')
  await page.getByRole('button', { name: 'Ver empresa: Fluxo Integrado' }).click()
  await expect(page.getByRole('dialog')).toContainText('Fluxo Integrado')
  expect((await sql('SELECT iniciada_em FROM empresa_vinculo WHERE empresa_id=$1', [empresa])).rows[0].iniciada_em).toBeNull()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Iniciar atendimento', exact: true }).click()
  expect((await sql('SELECT id FROM contato WHERE empresa_id=$1', [empresa])).rowCount).toBe(0)
  const hoje = (await sql("SELECT to_char((now() AT TIME ZONE 'America/Sao_Paulo')::date,'YYYY-MM-DD') AS dia")).rows[0].dia
  await page.getByLabel('Falei, pediu para ligar em outro momento', { exact: true }).check()
  await page.getByLabel('Próximo passo', { exact: true }).fill('Retorno da jornada integrada')
  await page.getByLabel('Data do próximo passo', { exact: true }).fill(hoje)
  await page.getByRole('button', { name: 'Registrar', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Atendimento registrado.' })).toBeVisible()
  await page.goto('/funil')
  await page.goto('/meu-dia')
  await expect(page.getByRole('main')).toContainText('Retorno da jornada integrada')
  await page.goto('/funil')
  await page.getByRole('button', { name: 'Marcar como Sem interesse', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Empresa marcada como Sem interesse')
  const historia = (await sql('SELECT * FROM contato WHERE empresa_id=$1', [empresa])).rows
  await page.goto('/fila/sem-interesse')
  await page.getByRole('button', { name: 'Retomar atendimento', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Atendimento retomado')
  expect((await sql('SELECT agenda_contato_id FROM empresa_vinculo WHERE empresa_id=$1', [empresa])).rows[0].agenda_contato_id).toBeNull()
  expect((await sql('SELECT * FROM contato WHERE empresa_id=$1', [empresa])).rows).toEqual(historia)
  await page.goto('/fila/atendimento/' + empresa)
  await page.getByLabel('Falei, tem interesse', { exact: true }).check()
  await page.getByRole('button', { name: 'Registrar', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Atendimento registrado.' })).toBeVisible()
  await page.goto('/funil')
  await page.getByRole('button', { name: 'Abrir no funil', exact: true }).click()
  await page.getByRole('button', { name: 'Registrar venda', exact: true }).click()
  await page.getByLabel('Valor em reais').fill('100,00')
  await page.getByLabel('Data da venda').fill(hoje)
  await page.getByRole('button', { name: 'Conferir venda' }).click()
  await page.getByRole('button', { name: 'Confirmar venda', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const antiga = await context.newPage()
  await antiga.goto('/carteira/' + empresa)
  await antiga.getByRole('button', { name: 'Registrar venda', exact: true }).click()
  await antiga.getByLabel('Valor em reais').fill('200,00')
  await antiga.getByLabel('Data da venda').fill(hoje)
  await antiga.getByLabel('Observação (opcional)').fill('Compra posterior preservada')
  await antiga.getByRole('button', { name: 'Conferir venda' }).click()
  await page.goto('/carteira/' + empresa)
  await page.getByRole('button', { name: 'Registrar atendimento', exact: true }).click()
  await page.getByLabel('Falei, não tem interesse', { exact: true }).check()
  await page.getByRole('button', { name: 'Registrar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Registrar venda', exact: true })).toBeDisabled()
  await antiga.getByRole('button', { name: 'Confirmar venda', exact: true }).click()
  await expect(antiga.getByRole('alert')).toContainText('Retome o atendimento')
  await expect(antiga.getByLabel('Valor em reais')).toHaveValue('200,00')
  await expect(antiga.getByLabel('Observação (opcional)')).toHaveValue('Compra posterior preservada')
  expect((await sql('SELECT id FROM venda WHERE empresa_id=$1', [empresa])).rowCount).toBe(1)
  await page.getByRole('button', { name: 'Retomar atendimento', exact: true }).click()
  await expect(page).toHaveURL(new RegExp('/fila/atendimento/' + empresa))
  await antiga.getByRole('button', { name: 'Confirmar venda', exact: true }).click()
  await expect(antiga.getByRole('dialog')).toHaveCount(0)
  expect((await sql('SELECT id FROM venda WHERE empresa_id=$1', [empresa])).rowCount).toBe(2)
  expect((await sql('SELECT id FROM negociacao WHERE empresa_id=$1 AND encerrada_em IS NULL', [empresa])).rowCount).toBe(0)
  await antiga.getByRole('tab', { name: 'Histórico', exact: true }).click()
  await expect(antiga.getByText('Venda registrada', { exact: true })).toHaveCount(2)
  await expect(antiga.getByText('Compra posterior preservada', { exact: true })).toBeVisible()
  await antiga.screenshot({ path: '.superpowers/sdd/2026-10-29-fluxo-comercial-unificado/task-9-captures/carteira-historico-integrado.png', fullPage: true })
  await antiga.close()
})
