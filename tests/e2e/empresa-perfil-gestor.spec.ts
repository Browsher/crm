import { expect, test } from '@playwright/test'
import { comAdmin } from '../../src/server/db/admin'
import { exigirAdminLocal } from './ambiente'

let empresaId: string
const fantasiaLonga = 'AuroraComercial'.repeat(6)
test.beforeAll(async () => {
  const url = process.env.DATABASE_URL_ADMIN
  if (!url) throw new Error('Execute pelo harness de E2E local')
  exigirAdminLocal(url)
  await comAdmin(url, async cliente => {
    await cliente.query('BEGIN')
    try {
      const { rows: [dono] } = await cliente.query<{ id: string }>("SELECT id FROM usuario WHERE email='vendedore2e@teste.local'")
      const { rows: [empresa] } = await cliente.query<{ id: string }>(`INSERT INTO empresa(cnpj,razao_social,nome_fantasia,telefone,contato_nome,email)
        VALUES('90909090909901','Perfil Gestor Aurora',$1,'11988776655','Marina','marina@teste.local') RETURNING id`, [fantasiaLonga])
      empresaId = empresa.id
      await cliente.query('INSERT INTO empresa_fila(empresa_id,vendedor_id) VALUES($1,$2)', [empresaId,dono.id])
      await cliente.query("INSERT INTO empresa_vinculo(empresa_id,vendedor_id,origem_inicial) VALUES($1,$2,'legado')",[empresaId,dono.id])
      await cliente.query(`WITH g AS (INSERT INTO grupo_importacao(nome) VALUES('Origem da ficha do gestor') RETURNING id)
        INSERT INTO grupo_importacao_empresa(grupo_id,empresa_id) SELECT id,$1 FROM g`, [empresaId])
      await cliente.query("SELECT set_config('app.usuario_id',$1,true)", [dono.id])
      const {rows:[contato]}=await cliente.query(`INSERT INTO contato(empresa_id,tipo,nota,proximo_passo,proximo_passo_data)
        VALUES($1,'acompanhamento','Conversa de teste registrada','Telefonar amanhã',(now() AT TIME ZONE 'America/Sao_Paulo')::date+1) RETURNING id`, [empresaId])
      await cliente.query('UPDATE empresa_vinculo SET agenda_contato_id=$2 WHERE empresa_id=$1',[empresaId,contato.id])
      await cliente.query('COMMIT')
    } catch (erro) { await cliente.query('ROLLBACK'); throw erro }
  })
})

test('gestor abre ficha lateral pela lista, consulta sem ações e volta mantendo a busca', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/login')
  await page.getByLabel('E-mail').fill('gestore2e@teste.local')
  await page.getByLabel('Senha', { exact: true }).fill('Senha-e2e-2026')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL('/gestao')
  const origem = '/empresas?q=Perfil+Gestor+Aurora&pagina=1'
  await page.goto(origem)
  const cards=page.getByRole('region',{name:'Empresas cadastradas'})
  await expect(cards).toContainText('Em atendimento')
  await expect(cards.getByRole('button',{name:/Iniciar|Retomar|Continuar atendimento/})).toHaveCount(0)
  const gatilho = cards.getByRole('button',{name:`Consulta rápida: ${fantasiaLonga}`,exact:true})
  await gatilho.click()
  const consulta = page.getByRole('dialog',{name:'Ver empresa',exact:true})
  await expect(consulta).toHaveAttribute('data-slot','painel-lateral-content')
  await expect(consulta).toContainText(fantasiaLonga)
  await expect(consulta.getByRole('button',{name:/Iniciar|Retomar|Registrar/})).toHaveCount(0)
  await consulta.getByRole('button',{name:'Cadastro e origem',exact:true}).click()
  await expect(consulta.getByRole('heading',{name:'Cadastro',exact:true})).toBeVisible()
  await consulta.getByRole('button',{name:'Voltar',exact:true}).click()
  await page.keyboard.press('Escape')
  await expect(gatilho).toBeFocused()
  const abrirFicha = cards.getByRole('link', { name: 'Ficha completa', exact: true })
  const fichaDireta = await abrirFicha.getAttribute('href')
  expect(fichaDireta).toMatch(new RegExp(`^/empresas/${empresaId}\\?`))
  await abrirFicha.click()
  const ficha = page.getByRole('dialog', { name: fantasiaLonga, exact: true })
  await expect(ficha).toHaveAttribute('data-slot', 'painel-lateral-content')
  await expect(ficha).toHaveCSS('width', '520px')
  await expect(page).toHaveURL(origem)
  const corpo = ficha.locator('[data-painel-corpo]')
  await expect(corpo.getByText(fantasiaLonga, { exact: true })).toBeVisible()
  expect(await corpo.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await expect(ficha.getByText('Marina', { exact: true })).toBeVisible()
  await expect(ficha.getByText('(11) 98877-6655', { exact: true })).toBeVisible()
  await expect(ficha.getByText('Origem da ficha do gestor', { exact: true })).toBeVisible()
  await ficha.getByRole('tab', { name: 'Histórico', exact: true }).click()
  await ficha.getByRole('button', { name: 'Expandir todos', exact: true }).click()
  await expect(ficha.getByText('Conversa de teste registrada', { exact: true })).toBeVisible()
  await expect(ficha.getByText('Por vendedore2e', { exact: true })).toBeVisible()
  await expect(ficha.locator('form')).toHaveCount(0)
  await expect(ficha.getByRole('button', { name: 'Registrar atendimento' })).toHaveCount(0)
  await ficha.getByRole('button', { name: 'Fechar', exact: true }).click()
  await expect(abrirFicha).toBeFocused()
  await expect(page).toHaveURL(origem)

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Tema de Empresas').selectOption('dark')
  await abrirFicha.press('Enter')
  await expect(ficha.getByRole('tab', { name: 'Dados da empresa', exact: true })).toHaveAttribute('aria-selected', 'true')
  expect(await ficha.boundingBox()).toMatchObject({ x: 0, y: 0, width: 390, height: 844 })
  expect(await corpo.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(ficha).toHaveCount(0)
  await expect(abrirFicha).toBeFocused()
  await expect(page).toHaveURL(origem)

  await page.goto(fichaDireta!)
  await expect(page.getByRole('heading', { name: fantasiaLonga, level: 1 })).toBeVisible()
  await page.getByRole('link', { name: 'Voltar para empresas', exact: true }).click()
  await expect(page).toHaveURL(origem)
  await page.goto('/empresas/00000000-0000-4000-8000-000000000000')
  await expect(page.getByText('404', { exact: true })).toBeVisible()
})

