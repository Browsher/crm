async function entrar(page: Page, apelido: string) {
  await page.goto('/login')
  await page.getByLabel('E-mail').fill(`${apelido}@teste.local`)
  await page.getByLabel('Senha', { exact:true }).fill('Senha-e2e-2026')
  await page.getByRole('button', { name:'Entrar', exact:true }).click()
  await expect(page).toHaveURL(apelido.includes('gestor') ? '/gestao' : '/meu-dia')
}
async function tabAte(page:Page,alvo:Locator) {
  for(let i=0;i<140;i++) {
    await page.keyboard.press('Tab')
    if(await alvo.evaluate(elemento=>elemento===document.activeElement)) return
  }
  throw new Error('O teclado não alcançou o controle esperado')
}
async function estadoImportacao() {
  return comBancoGrupos(async c => {
    const estado = []
    for (const tabela of ['empresa','empresa_origem_google','grupo_importacao','grupo_importacao_empresa']) estado.push((await c.query(`SELECT * FROM ${tabela} ORDER BY 1,2`)).rows)
    return estado
  })
}
test.beforeAll(async () => {
  const banco = bancoGruposDoHarness()
  for (const [papel,apelido] of [['gestor','catalogogestore2e'],['vendedor','catalogovendedore2e']] as const) {
    if (!(await banco.sql('SELECT id FROM usuario WHERE email=$1',[`${apelido}@teste.local`])).length) await criarUsuarioComSenha(banco,papel,apelido,'Senha-e2e-2026')
  }
})
