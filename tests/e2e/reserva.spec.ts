import { expect, test, type Page } from '@playwright/test'
async function entrar(page:Page,usuario:string) {
 await page.goto('/login');await page.getByLabel('E-mail').fill(usuario+'@teste.local');await page.getByLabel('Senha',{exact:true}).fill('Senha-e2e-2026');await page.getByRole('button',{name:'Entrar',exact:true}).click();await expect(page).toHaveURL('/meu-dia')
}
const card=(page:Page,nome:string)=>page.locator('[data-slot=card]').filter({has:page.getByRole('heading',{name:nome,exact:true})})

test('vínculo permanente mantém rascunhos separados e recusa aba antiga sem reserva',async({page,context})=>{
 await entrar(page,'reservaae2e');await page.goto('/fila/localizar?nome=Reserva%20E2E')
 await card(page,'Reserva E2E A').getByRole('button',{name:'Iniciar atendimento',exact:true}).click()
 await expect(page).toHaveURL(/\/fila\/atendimento\//)
 const urlA=page.url()
 await page.getByLabel('Nota',{exact:true}).fill('Rascunho de A')
 await page.goto('/fila/localizar?nome=Reserva%20E2E')
 await card(page,'Reserva E2E B').getByRole('button',{name:'Iniciar atendimento',exact:true}).click()
 await page.getByLabel('Nota',{exact:true}).fill('Rascunho de B')
 await page.goto(urlA);await expect(page.getByLabel('Nota',{exact:true})).toHaveValue('Rascunho de A')
 const antiga=await context.newPage();await antiga.goto(urlA)
 await antiga.getByLabel('Nota',{exact:true}).fill('Texto da aba antiga')
 await page.getByLabel('Liguei, não falei com ninguém',{exact:true}).check()
 await page.getByRole('button',{name:'Registrar',exact:true}).click()
 await expect(page.getByLabel('Nota',{exact:true})).toHaveValue('')
 await antiga.getByRole('button',{name:'Registrar',exact:true}).click()
 await expect(antiga.locator('[data-slot=alert]')).toContainText('outra aba')
 await expect(antiga.getByLabel('Nota',{exact:true})).toHaveValue('Texto da aba antiga')
 await antiga.close()
})
test('passagem de 31 minutos não expira o atendimento nem apaga rascunho',async({page})=>{
 await entrar(page,'reservabe2e');await page.goto('/fila/localizar?nome=Reserva%20Unica')
 await card(page,'Reserva Unica E2E').getByRole('button',{name:'Iniciar atendimento',exact:true}).click()
 await page.getByLabel('Nota',{exact:true}).fill('Texto que precisa sobreviver')
 await page.clock.install();await page.clock.fastForward(31*60*1000)
 await expect(page.getByRole('button',{name:'Registrar',exact:true})).toBeEnabled()
 await expect(page.getByLabel('Nota',{exact:true})).toHaveValue('Texto que precisa sobreviver')
 await expect(page.getByRole('button',{name:'Tentar reservar novamente',exact:true})).toHaveCount(0)
})
